export function getCircadianTip() {
  const hour = new Date().getHours();
  return CIRCADIAN_TIPS.find((t) => hour >= t.hour[0] && hour < t.hour[1]) || CIRCADIAN_TIPS[0];
}

export function randomFact(filterTag = null) {
  const pool = filterTag ? BRAIN_FACTS.filter((f) => f.tag === filterTag) : BRAIN_FACTS;
  if (!pool.length) return BRAIN_FACTS[0];
  return pool[Math.floor(Math.random() * pool.length)];
}

export function createFactRotator(intervalMs = 14000) {
  const subscribers = new Set();
  let current = randomFact();
  let timer = 0;

  function pick() {
    const next = randomFact();
    current = next.fact === current.fact ? randomFact() : next;
    subscribers.forEach((cb) => cb(current));
  }

  function start() {
    stop();
    timer = window.setInterval(pick, intervalMs);
  }

  function stop() {
    if (timer) window.clearInterval(timer);
    timer = 0;
  }

  function onChange(cb) {
    subscribers.add(cb);
    cb(current);
    return () => subscribers.delete(cb);
  }

  return { start, stop, onChange, get current() { return current; }, pick };
}
