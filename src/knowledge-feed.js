/**
 * Deterministic hash from YYYY-MM-DD + offset so today's 4-card brief
 * is stable throughout the day, with 1 card per domain (Science, Math, AI, Longevity).
 */
export function getDailyKnowledgeBrief(offset = 0) {
  const today = new Date().toISOString().slice(0, 10);
  let seed = offset * 13;
  for (let i = 0; i < today.length; i += 1) {
    seed = (seed * 31 + today.charCodeAt(i)) % 9973;
  }
  const domains = ["science", "math", "ai", "longevity"];
  return domains.map((dom, idx) => {
    const pool = KNOWLEDGE_CARDS.filter((c) => c.domain === dom);
    return pool[(seed + idx * 5) % pool.length];
  });
}

export function getKnowledgeByDomain(domain, offset = 0) {
  if (!domain || domain === "all") return getDailyKnowledgeBrief(offset);
  const pool = KNOWLEDGE_CARDS.filter((c) => c.domain === domain);
  if (offset === 0) return pool.slice(0, 4);
  const shift = offset % pool.length;
  return [...pool.slice(shift), ...pool.slice(0, shift)].slice(0, 4);
}

